def calculate_hedge_ev(side, bid_price, ledger_data):
    if ledger_data is None: return 0.0, False
    net_side = ledger_data.get("net_side", "flat"); net_qty = ledger_data.get("net_qty", 0)
    if net_qty == 0 or net_side == "flat" or net_side == side: return 0.0, False
    opposite_avg = ledger_data.get("yes_avg_price", 0.0) if side == "no" else ledger_data.get("no_avg_price", 0.0)
    if opposite_avg <= 0: return 0.0, False
    hedge_ev = (100.0 - opposite_avg - bid_price) / 100.0
    if hedge_ev <= 0: return 0.0, True
    return hedge_ev, True

def get_pairing_mode(ticker, ledger, net_position):
    ledger_data = ledger.get(ticker)
    net_qty = ledger_data.get("net_qty", 0) if ledger_data else abs(net_position)
    imbalance_ratio = net_qty / MAX_NET_PER_MARKET if MAX_NET_PER_MARKET > 0 else 0.0
    if net_qty >= PAIRING_MODE_NET_AGGRESSIVE: return "aggressive_pairing", imbalance_ratio
    elif net_qty >= PAIRING_MODE_NET_FLOOR: return "pairing", imbalance_ratio
    return "normal", imbalance_ratio

def get_effective_side_multiplier(base_side_mult, side, pairing_mode, net_side):
    if pairing_mode == "normal" or net_side == side or net_side == "flat": return base_side_mult
    if pairing_mode == "aggressive_pairing": return max(base_side_mult, 1.5)
    elif pairing_mode == "pairing": return max(base_side_mult, 1.0)
    return base_side_mult

def calculate_ledger_position_multiplier(ticker, side, ledger, fallback_net_position):
    data = ledger.get(ticker)
    if data is None: return calculate_position_multiplier(fallback_net_position, side), "no_ledger_data", 0.0
    paired_qty = data["paired_qty"]; net_qty = data["net_qty"]; net_side = data["net_side"]
    side_qty = data["yes_qty"] if side == "yes" else data["no_qty"]
    if side_qty >= MAX_PAIRED_PER_MARKET: return 0.0, f"hard_cap_{side}_qty={side_qty}", 0.0
    if net_side == side and net_qty > 0:
        if net_qty >= MAX_NET_PER_MARKET: return 0.0, f"net_cap_{side}={net_qty}", 0.0
        elif net_qty >= MAX_NET_PER_MARKET * 0.7:
            remaining_frac = (MAX_NET_PER_MARKET - net_qty) / (MAX_NET_PER_MARKET * 0.3)
            return max(0.1, remaining_frac), f"net_rampdown_{side}={net_qty}", 0.0
        return 1.0, f"net_ok_{side}={net_qty}", 0.0
    elif net_side != side and net_side != "flat" and net_qty > 0:
        if net_qty >= PAIRING_MODE_NET_AGGRESSIVE: return 2.0, "aggressive_pair_boost", 1.5
        elif net_qty >= PAIRING_MODE_NET_FLOOR: return 1.5, "pair_boost", 1.0
        elif net_qty >= int(MAX_NET_PER_MARKET * 0.25): return 1.2, "mild_pair_boost", 0.8
        return 1.0, "net_balanced", 0.0
    if paired_qty > MAX_PAIRED_PER_MARKET * 0.6 and data["paired_edge"] > 3:
        return 0.6, "diminishing_returns", 0.0
    return 1.0, "default", 0.0

def calculate_position_multiplier(net_position, side):
    abs_pos = abs(net_position)
    if net_position > 0:
        if side == 'yes':
            if abs_pos >= POSITION_STOP_THRESHOLD: return 0.0
            elif abs_pos >= POSITION_MODERATE_THRESHOLD: return 1.0 - (abs_pos - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
            return 1.0
        else:
            if abs_pos >= POSITION_STOP_THRESHOLD: return 2.0
            elif abs_pos >= POSITION_MODERATE_THRESHOLD: return 1.0 + (abs_pos - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
            return 1.0
    elif net_position < 0:
        if side == 'no':
            if abs_pos >= POSITION_STOP_THRESHOLD: return 0.0
            elif abs_pos >= POSITION_MODERATE_THRESHOLD: return 1.0 - (abs_pos - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
            return 1.0
        else:
            if abs_pos >= POSITION_STOP_THRESHOLD: return 2.0
            elif abs_pos >= POSITION_MODERATE_THRESHOLD: return 1.0 + (abs_pos - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
            return 1.0
    return 1.0

