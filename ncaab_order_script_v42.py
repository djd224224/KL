def submit_orders_sequential(orders):
    results = []; total = len(orders); print(f"Submitting {total} orders..."); start = time.time()
    for i, op in enumerate(orders):
        if i % 50 == 0 and i > 0: print(f"  Progress: {i}/{total} ({i*100//total}%)")
        metadata = {k: op.pop(k) for k in ["run_id","model_version","spread_config","spread_cents","time_multiplier",
            "volume_multiplier","position_multiplier","side_multiplier","boost_multiplier","total_multiplier",
            "base_contracts","hours_until_event","open_interest","net_position","ev","standalone_ev","hedge_ev",
            "is_pairing_order","pairing_mode","p_hat","pricing_strategy","safe_mode","event_ticker"] if k in op}
        metadata["sweet_spot_applied"] = op.pop("sweet_spot_applied", False)
        ts = datetime.now(UTC).isoformat()
        try:
            response = exchange_client.create_order(**op)
            results.append({"ok": True, "ticker": op["ticker"], "side": op["side"],
                "price": op.get("yes_price") or op.get("no_price"), "contracts": op["count"],
                "order_id": response.get("order",{}).get("order_id"), "error": None, "created_at": ts, **metadata})
        except Exception as e:
            results.append({"ok": False, "ticker": op["ticker"], "side": op["side"],
                "price": op.get("yes_price") or op.get("no_price"), "contracts": op["count"],
                "error": str(e), "order_id": None, "created_at": ts, **metadata})
        time.sleep(SLEEP_BETWEEN_ORDERS)
    elapsed = time.time() - start; print(f"✓ Completed in {elapsed:.1f}s\n"); return results

