def parse_orderbook(orderbook_data):
    if not orderbook_data: return None, None
    best_bid = max(level[0] for level in orderbook_data)
    idx = next(i for i, level in enumerate(orderbook_data) if level[0] == best_bid)
    return best_bid, orderbook_data[idx][1]

def calculate_hybrid_price_bayesian(market_mid, market_yes_rate, market_sample_size,
                                     team_1_yes_rate, team_1_sample_size, team_2_yes_rate, team_2_sample_size):
    intermediates = {}; market_mid_rate = market_mid / 100
    if market_yes_rate is None or pd.isna(market_yes_rate): return market_mid_rate, {"fallback": "no_market_yes_rate"}
    team_rates, team_weights = [], []
    if team_1_sample_size > 0 and team_1_yes_rate is not None and not pd.isna(team_1_yes_rate): team_rates.append(team_1_yes_rate); team_weights.append(team_1_sample_size)
    if team_2_sample_size > 0 and team_2_yes_rate is not None and not pd.isna(team_2_yes_rate): team_rates.append(team_2_yes_rate); team_weights.append(team_2_sample_size)
    if team_rates: ttw = sum(team_weights); avg_team = sum(r*w for r,w in zip(team_rates, team_weights))/ttw; combined_n = ttw
    else: avg_team = market_yes_rate; combined_n = 0
    cred = min(combined_n / BAYESIAN_K, 1.0) if combined_n > 0 else 0.0
    posterior = (1-cred)*market_yes_rate + cred*avg_team if combined_n > 0 else market_yes_rate
    n = max(market_sample_size, 0); recency = 2 ** (-n / BAYESIAN_RECENCY_HALFLIFE_GAMES)
    hw = BAYESIAN_HISTORICAL_WEIGHT * (1.0 - 0.5*(1.0-recency)); mw = BAYESIAN_MARKET_WEIGHT
    tw = mw + hw; mw /= tw; hw /= tw
    return mw * market_mid_rate + hw * posterior, intermediates

def calculate_bid_price(market_mid_yes, market_yes_rate, team_1_yes_rate, team_1_sample_size,
                        team_2_yes_rate, team_2_sample_size, market_sample_size, strategy):
    if strategy == 'hybrid':
        if market_mid_yes is None:
            if market_yes_rate is None or pd.isna(market_yes_rate): return None, None, {}
            yp = cents_from_rate(market_yes_rate); return yp, 100-yp, {"fallback": "no_orderbook"}
        hyb, inter = calculate_hybrid_price_bayesian(market_mid_yes, market_yes_rate, market_sample_size,
            team_1_yes_rate, team_1_sample_size, team_2_yes_rate, team_2_sample_size)
        yp = int(hyb * 100); return yp, 100-yp, inter
    elif strategy == 'market':
        if market_mid_yes is not None: yp = int(round(market_mid_yes)); return yp, 100-yp, {}
        return None, None, {}
    elif strategy == 'historical':
        if market_yes_rate is None or pd.isna(market_yes_rate): return None, None, {}
        yp = cents_from_rate(market_yes_rate); return yp, 100-yp, {}
    raise ValueError(f"Unknown strategy: {strategy}")

