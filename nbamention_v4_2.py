def get_pairing_mode(
    ticker: str,
    ledger: Dict[str, Dict[str, Any]],
    net_position: int,
) -> Tuple[str, float]:
    """
    Determine pairing mode for a market.

    Returns:
      (mode, imbalance_ratio)
      mode: "normal", "pairing", or "aggressive_pairing"
      imbalance_ratio: 0.0 to 1.0+ (net_qty / MAX_NET_PER_MARKET)
    """
    ledger_data = ledger.get(ticker)

    # Use ledger net_qty if available, else fall back to API net_position
    if ledger_data is not None:
        net_qty = ledger_data.get("net_qty", 0)
    else:
        net_qty = abs(net_position)

    imbalance_ratio = net_qty / MAX_NET_PER_MARKET if MAX_NET_PER_MARKET > 0 else 0.0

    if net_qty >= PAIRING_MODE_NET_AGGRESSIVE:
        return "aggressive_pairing", imbalance_ratio
    elif net_qty >= PAIRING_MODE_NET_FLOOR:
        return "pairing", imbalance_ratio
    else:
        return "normal", imbalance_ratio


# =====================================================================
# [v4.2-5] SIDE MULTIPLIER OVERRIDE FOR HEDGING
# =====================================================================

def get_effective_side_multiplier(
    base_side_mult: float,
    side: str,
    pairing_mode: str,
    net_side: str,
) -> float:
    """
    Override side multiplier when in pairing mode.

    Only overrides for the hedge side (opposite of net exposure).
    The side that caused the imbalance keeps its normal multiplier.
    """
    if pairing_mode == "normal":
        return base_side_mult

    # Only override if this is the hedge side
    if net_side == side or net_side == "flat":
        return base_side_mult

    # This is the opposite side — we need fills here
    if pairing_mode == "aggressive_pairing":
        return max(base_side_mult, 1.5)
    elif pairing_mode == "pairing":
        return max(base_side_mult, 1.0)

    return base_side_mult


