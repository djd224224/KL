    print(f"  df_summary: {df_summary.shape} (historical stats per market_code)")
    print(f"  df_summary_rolling: {df_summary_rolling.shape} (time-series per market_code)")
    print(f"  df_summary_rolling_by_team: {df_summary_rolling_by_team.shape} (time-series per team)")

    return df_results, df_summary, df_summary_rolling, df_summary_rolling_by_team


