def fetch_fills_from_bq(
    bq_client,
    project_id: str,
    dataset_id: str,
    series_ticker: str = "KXNBAMENTION",
    lookback_days: int = 30,
) -> pd.DataFrame:
    """Pull successful order fills from BigQuery."""
    table_id = f"{project_id}.{dataset_id}.{series_ticker}_orders"

    query = f"""
    SELECT
        ticker,
        side,
        price,
        contracts,
        order_id,
        client_order_id,
        created_at,
        ev,
        p_hat,
        total_multiplier,
        spread_config,
        spread_cents,
        sweet_spot_applied,
        pricing_strategy,
        model_version,
        run_id
    FROM `{table_id}`
    WHERE ok = TRUE
      AND created_at >= TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL {lookback_days} DAY)
    ORDER BY ticker, created_at
    """

    print(f"  Fetching fills from {table_id} (last {lookback_days} days)...")

    try:
        df = bq_client.query(query).to_dataframe()
        print(f"  ✓ Loaded {len(df)} fills across {df['ticker'].nunique()} markets")
        return df
    except Exception as e:
        print(f"  ✗ Error fetching fills: {e}")
        return pd.DataFrame()


def fetch_fills_from_api(
    exchange_client_ref,
    series_ticker: str = "KXNBAMENTION",
) -> pd.DataFrame:
    """
    Pull fills directly from the Kalshi API.
    More accurate than BQ for partial fills.
    """
    print(f"  Fetching fills from Kalshi API for {series_ticker}...")

    all_fills = []
    cursor = None
    page = 0

    while True:
        page += 1
        params = {"limit": 1000}
        if cursor:
            params["cursor"] = cursor

        try:
            response = exchange_client_ref.get_fills(**params)
        except Exception as e:
            print(f"  ✗ Error on page {page}: {e}")
            break

        batch = response.get("fills", [])
        if not batch:
            break

        series_fills = [
            f for f in batch
            if f.get("ticker", "").startswith(series_ticker)
        ]
        all_fills.extend(series_fills)

        cursor = response.get("cursor")
        if not cursor:
            break

        if page % 10 == 0:
            print(f"    Page {page}: {len(all_fills)} {series_ticker} fills so far")

    if not all_fills:
        print(f"  No fills found for {series_ticker}")
        return pd.DataFrame()

    df = pd.DataFrame(all_fills)
    print(f"  ✓ Loaded {len(df)} fills across {df['ticker'].nunique()} markets from API")
    print(f"  API fill columns: {list(df.columns)}")

    # Normalize column names — Kalshi API uses different names than our BQ table
    # API returns: count, yes_price, side, ticker, ...
    # Ledger expects: contracts, price, side, ticker

    # Map 'count' → 'contracts'
    if 'count' in df.columns and 'contracts' not in df.columns:
        df = df.rename(columns={'count': 'contracts'})
        print(f"  Mapped 'count' → 'contracts'")

    # DEBUG: print columns and sample rows so we can verify price format
    print(f"  Columns: {list(df.columns)}")
    sample = df.head(3)
    for _, row in sample.iterrows():
        print(f"    Sample fill: ticker={row.get('ticker')}, side={row.get('side')}, "
              f"yes_price={row.get('yes_price')}, no_price={row.get('no_price', 'N/A')}, "
              f"count/contracts={row.get('contracts', row.get('count', 'N/A'))}")

    # Build unified 'price' column = the price paid for THAT SIDE in cents
    # ALWAYS derive from yes_price (most reliable field from Kalshi API)
    # YES fill: price = yes_price
    # NO fill:  price = 100 - yes_price (since YES + NO = 100)
    if 'yes_price' in df.columns:
        yes_prices = pd.to_numeric(df['yes_price'], errors='coerce')
        max_val = yes_prices.max()

        if max_val <= 1.0:
            # Decimal format (0.60 = 60¢)
            df['price'] = df.apply(
                lambda row: float(row['yes_price']) if row.get('side') == 'yes'
                            else (1.0 - float(row['yes_price'])),
                axis=1
            )
            print(f"  Built 'price' from yes_price (decimal, max={max_val:.4f}): YES=yes_price, NO=1.0-yes_price")
        else:
            # Cents format (60 = 60¢)
            df['price'] = df.apply(
                lambda row: float(row['yes_price']) if row.get('side') == 'yes'
                            else (100.0 - float(row['yes_price'])),
                axis=1
            )
            print(f"  Built 'price' from yes_price (cents, max={max_val:.1f}): YES=yes_price, NO=100-yes_price")

        # Verify with sample
        for side_check in ['yes', 'no']:
            side_rows = df[df['side'] == side_check].head(2)
            for _, row in side_rows.iterrows():
                print(f"    Verify: {row.get('ticker')} side={side_check} "
                      f"yes_price={row.get('yes_price')} → price={row['price']:.2f}")
    elif 'price' in df.columns:
        print(f"  Using existing 'price' column")
    else:
        print(f"  ⚠️ No price column found! Available: {list(df.columns)}")

    return df


def build_position_ledger(
    fills_df: pd.DataFrame,
    price_col: str = "price",
    contracts_col: str = "contracts",
) -> Dict[str, Dict[str, Any]]:
    """
    Build per-market ledger from fills.

    Returns dict keyed by ticker with:
      yes_qty, no_qty, yes_avg_price, no_avg_price,
      paired_qty, net_qty, net_side, paired_cost, paired_edge,
      profit_if_yes, profit_if_no, worst_case, paired_profit
    """
    if fills_df is None or len(fills_df) == 0:
        print("  No fills to build ledger from")
        return {}

    ledger: Dict[str, Dict[str, Any]] = {}

    df = fills_df.copy()
    df[price_col] = pd.to_numeric(df[price_col], errors="coerce")
    df[contracts_col] = pd.to_numeric(df[contracts_col], errors="coerce")
    df = df.dropna(subset=[price_col, contracts_col])

    # Normalize prices to CENTS (0–100 scale)
    # Kalshi API returns prices as decimals (0.58) or small integers
    # If max price <= 1.0, it's decimal format → multiply by 100
    max_price_val = df[price_col].max()
    if max_price_val <= 1.0:
        print(f"  ⚠️ Prices appear to be in decimal format (max={max_price_val:.4f}) — converting to cents")
        df[price_col] = df[price_col] * 100
    elif max_price_val <= 100:
        print(f"  ✓ Prices appear to be in cents (max={max_price_val:.1f})")
    else:
        print(f"  ⚠️ Unexpected price range (max={max_price_val:.1f}) — using as-is")

    for ticker, group in df.groupby("ticker"):
        yes_fills = group[group["side"] == "yes"]
        no_fills = group[group["side"] == "no"]

        yes_qty = int(yes_fills[contracts_col].sum())
        no_qty = int(no_fills[contracts_col].sum())

        yes_avg_price = (
            (yes_fills[price_col] * yes_fills[contracts_col]).sum()
            / yes_fills[contracts_col].sum()
            if yes_qty > 0 else 0.0
        )
        no_avg_price = (
            (no_fills[price_col] * no_fills[contracts_col]).sum()
            / no_fills[contracts_col].sum()
            if no_qty > 0 else 0.0
        )

        paired_qty = min(yes_qty, no_qty)
        net_qty = abs(yes_qty - no_qty)
        net_side = "yes" if yes_qty > no_qty else ("no" if no_qty > yes_qty else "flat")

        paired_cost = yes_avg_price + no_avg_price if paired_qty > 0 else 0.0
        paired_edge = 100.0 - paired_cost if paired_qty > 0 else 0.0

        yes_total_cost = yes_avg_price * yes_qty
        no_total_cost = no_avg_price * no_qty

        profit_if_yes = (yes_qty * 100) - yes_total_cost - no_total_cost
        profit_if_no = (no_qty * 100) - yes_total_cost - no_total_cost
        worst_case = min(profit_if_yes, profit_if_no)

        ledger[ticker] = {
            "yes_qty": yes_qty,
            "no_qty": no_qty,
            "yes_avg_price": round(yes_avg_price, 2),
            "no_avg_price": round(no_avg_price, 2),
            "paired_qty": paired_qty,
            "net_qty": net_qty,
            "net_side": net_side,
            "paired_cost": round(paired_cost, 2),
            "paired_edge": round(paired_edge, 2),
            "yes_total_cost": round(yes_total_cost, 2),
            "no_total_cost": round(no_total_cost, 2),
            "profit_if_yes_cents": round(profit_if_yes, 2),
            "profit_if_no_cents": round(profit_if_no, 2),
            "worst_case_cents": round(worst_case, 2),
            "profit_if_yes": round(profit_if_yes / 100, 2),
            "profit_if_no": round(profit_if_no / 100, 2),
            "worst_case": round(worst_case / 100, 2),
            "paired_profit": round(paired_edge * paired_qty / 100, 2),
        }

    print(f"  ✓ Built ledger for {len(ledger)} markets")
    return ledger


