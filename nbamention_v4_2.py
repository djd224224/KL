def calculate_position_multiplier(net_position: int, side: str) -> float:
    """
    Fallback position multiplier when ledger is unavailable.
    Net position > 0 = long YES; < 0 = long NO.
    """
    abs_position = abs(net_position)

    if net_position > 0:
        if side == 'yes':
            if abs_position >= POSITION_STOP_THRESHOLD:
                return 0.0
            elif abs_position >= POSITION_MODERATE_THRESHOLD:
                progress = (abs_position - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
                return 1.0 - progress
            else:
                return 1.0
        else:
            if abs_position >= POSITION_STOP_THRESHOLD:
                return 2.0
            elif abs_position >= POSITION_MODERATE_THRESHOLD:
                progress = (abs_position - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
                return 1.0 + progress
            else:
                return 1.0

    elif net_position < 0:
        if side == 'no':
            if abs_position >= POSITION_STOP_THRESHOLD:
                return 0.0
            elif abs_position >= POSITION_MODERATE_THRESHOLD:
                progress = (abs_position - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
                return 1.0 - progress
            else:
                return 1.0
        else:
            if abs_position >= POSITION_STOP_THRESHOLD:
                return 2.0
            elif abs_position >= POSITION_MODERATE_THRESHOLD:
                progress = (abs_position - POSITION_MODERATE_THRESHOLD) / (POSITION_STOP_THRESHOLD - POSITION_MODERATE_THRESHOLD)
                return 1.0 + progress
            else:
                return 1.0

    else:
        return 1.0


