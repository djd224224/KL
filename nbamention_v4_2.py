# =====================================================================
# [v4.2-2] HEDGE-ADJUSTED EV CALCULATION
# =====================================================================

def calculate_hedge_ev(
    side: str,
    bid_price: int,
    ledger_data: Optional[Dict[str, Any]],
) -> Tuple[float, bool]:
    """
    Calculate the hedge EV for a pairing order.

    If we're net YES and buying NO, the hedge value is:
      hedge_ev = (100 - yes_avg_price - no_bid_price) / 100
    This is the spread we lock in per paired contract.

    CRITICAL: Only returns positive hedge_ev. If the spread locks in a
    loss (paired_cost > 100), returns 0.0 so the order must pass on
    standalone EV alone. We never hedge into a negative-profit lock.

    Returns (hedge_ev, is_pairing_order)
    """
    if ledger_data is None:
        return 0.0, False

    net_side = ledger_data.get("net_side", "flat")
    net_qty = ledger_data.get("net_qty", 0)

    # Only applies when we're buying the OPPOSITE side of our net
    if net_qty == 0 or net_side == "flat":
        return 0.0, False

    if net_side == side:
        # Adding to the same side — not a hedge
        return 0.0, False

    # We're pairing: buying opposite side
    if side == "no":
        # We're net YES, buying NO to pair
        opposite_avg = ledger_data.get("yes_avg_price", 0.0)
    else:
        # We're net NO, buying YES to pair
        opposite_avg = ledger_data.get("no_avg_price", 0.0)

    # Sanity check: opposite_avg should be in cents (1–99 range)
    if opposite_avg <= 0:
        return 0.0, False

    hedge_ev = (100.0 - opposite_avg - bid_price) / 100.0

    # ONLY return positive hedge_ev — never lock in a loss
    if hedge_ev <= 0:
        return 0.0, True  # Still a pairing order, but no hedge value

    return hedge_ev, True


