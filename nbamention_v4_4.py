    yes_side_mult = get_effective_side_multiplier(yes_side_mult_base, "yes", pairing_mode_str, net_side)
    no_side_mult = get_effective_side_multiplier(no_side_mult_base, "no", pairing_mode_str, net_side)

    if yes_side_mult != 1.0 and yes_side_mult == yes_side_mult_base:
        label = "⛔ BLOCKED" if yes_side_mult == 0.0 else f"📉 {yes_side_mult:.1f}x"
        print(f"    {label} YES for {ticker_part_3_market_code}")
    if no_side_mult != 1.0 and no_side_mult == no_side_mult_base:
        label = "⛔ BLOCKED" if no_side_mult == 0.0 else f"📉 {no_side_mult:.1f}x" if no_side_mult < 1.0 else f"🚀 {no_side_mult:.1f}x"
