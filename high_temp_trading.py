def _nws_get(url, retries=3, timeout=10):
    """GET with retry — NWS API is flaky about timeouts."""
    last = None
    for _ in range(retries):
        try:
            r = requests.get(url, headers=NWS_HEADERS, timeout=timeout)
            r.raise_for_status()
            return r.json()
        except Exception as e:
            last = e
            time.sleep(1)
    raise last


