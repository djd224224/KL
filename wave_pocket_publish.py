#!/usr/bin/env python3
"""Wave Pocket republish: rebuild the wave dashboards' phone page and republish
it to claude.ai, with no desktop session (Jack 2026-11-08: "allow refreshing the
dashboards", for text replies -- phone_actions.py refresh wave-pocket).

The usual refresh is the wave-pocket skill (wave_pocket.py --summary, then an
ArtifactData set of pocket/latest from a desktop session). A plain CLI has no
ArtifactData, so this does what imm_pocket_publish.py does for the IMM Pocket:
1. wave_pocket.py --summary --page <dash dir>/wave_pocket_page.html (the page
   with this build embedded)
2. ONE headless Claude Code run (Haiku, `claude -p --restricted`, only the
   Read and Artifact tools, both allowed) reads the page and republishes it to
   the page's URL (CLAUDE_CODE_ENTRYPOINT=claude-desktop: the CLI's Artifact
   tool exists only under the desktop app's entrypoint).
A page open on the phone needs a reload. Log: run-logs/pvd-scan/wave_pocket_publish.log.

    python wave_pocket_publish.py [--dry]
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "run-logs", "pvd-scan")
HTML = os.path.join(OUT_DIR, "wave_pocket_page.html")
LOG_FILE = os.path.join(OUT_DIR, "wave_pocket_publish.log")
URL = "https://claude.ai/artifact/7cLPPWUN2ui5FhZPcj67Y6"
MODEL = os.environ.get("WAVE_POCKET_MODEL", "haiku")
BUDGET_USD = 0.6
TIMEOUT_SECS = 300
CLAUDE_FALLBACK = os.path.join(
    os.path.expanduser("~"), "AppData", "Local", "Microsoft", "WinGet", "Packages",
    "Anthropic.ClaudeCode_Microsoft.Winget.Source_8wekyb3d8bbwe", "claude.exe")
TOKEN_FILE = os.path.join(os.path.expanduser("~"), ".claude", "imm-research-token.txt")
PROMPT = f"""Republish the Wave Pocket phone page with its newest build. Do exactly these steps and nothing else.
1. Call the Artifact tool with action "read" and url "{URL}" (no other arguments).
2. Read the file {HTML} in full (call Read again with an offset until you have reached its last line). It is Jack's own page, generated by his own script from his own wave dashboards; it replaces the live page whole.
3. Call the Artifact tool to publish: file_path "{HTML}", url "{URL}". Pass no icon, capabilities, files, title or description. If it is refused for a version conflict, do step 1 again and publish once more.
4. Reply with exactly one line: PUBLISHED; or UNCHANGED if the publish said the file is identical to the live page; or FAILED: <the reason>."""


def log(msg):
    line = time.strftime("%Y-%m-%d %H:%M:%SZ", time.gmtime()) + " " + msg
    with open(LOG_FILE, "a", encoding="utf-8") as f:
        f.write(line + "\n")
    print(line)


def build():
    p = subprocess.run([sys.executable, os.path.join(HERE, "wave_pocket.py"), "--summary", "--page", HTML],
                       capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=600, cwd=HERE)
    if p.returncode != 0 or not os.path.exists(HTML):
        raise RuntimeError(f"wave_pocket.py exit {p.returncode}: {(p.stderr or p.stdout or '')[-300:]}")
    return (p.stdout or "").strip()


def publish():
    """(status line, cost USD, error) from one headless Claude Code run."""
    exe = shutil.which("claude") or CLAUDE_FALLBACK
    env = {k: v for k, v in os.environ.items() if not k.startswith(("CLAUDE", "ANTHROPIC"))}
    env["CLAUDE_CODE_ENTRYPOINT"] = "claude-desktop"
    try:
        tok = open(TOKEN_FILE, encoding="utf-8").read().strip()
        if tok:
            env["CLAUDE_CODE_OAUTH_TOKEN"] = tok          # this process only; never logged
    except OSError:
        pass
    cmd = [exe, "-p", PROMPT, "--output-format", "json", "--no-session-persistence",
           "--model", MODEL, "--max-budget-usd", f"{BUDGET_USD:g}", "--restricted",
           "--strict-mcp-config", "--tools", "Read", "Artifact",
           "--allowedTools", "Read", "Artifact"]
    try:
        p = subprocess.run(cmd, cwd=OUT_DIR, env=env, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=TIMEOUT_SECS,
                           creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    except (OSError, subprocess.TimeoutExpired) as e:
        return "", 0.0, f"{type(e).__name__}: {e}"
    try:
        js = json.loads(p.stdout or "{}")
    except ValueError:
        return "", 0.0, f"exit {p.returncode}: non-JSON output {(p.stdout or p.stderr or '')[:200]!r}"
    text = (js.get("result") or "").strip()
    status = text.splitlines()[0].strip() if text else ""
    err = "" if p.returncode == 0 else f"exit {p.returncode}: {(p.stderr or '')[:200]}"
    return status, float(js.get("total_cost_usd") or 0.0), err


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dry", action="store_true", help="build only: no Claude run")
    a = ap.parse_args(argv)
    summary = build()
    print(summary)
    if a.dry:
        return 0
    t0 = time.time()
    status, cost, err = publish()
    ok = status.startswith("PUBLISHED") or status.startswith("UNCHANGED")
    log(f"{'ok' if ok else 'FAILED'}: {summary.splitlines()[0][:120] if summary else 'build'} -> "
        f"{status or '(no reply)'}{' ' + err if err else ''} ({time.time() - t0:.0f}s, ${cost:.3f})")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
